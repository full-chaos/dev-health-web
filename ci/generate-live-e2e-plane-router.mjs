#!/usr/bin/env node
// CHAOS-7001: derive live-e2e's traefik plane-split router config from
// dev-health-ops's OWN ci/go_served_paths.tsv -- the same ledger prod's
// ingress and bigboy's generate-plane-split-router.py already read, never a
// hand-maintained path list here. live-e2e has no k8s Ingress and no bigboy
// docker network, so unlike bigboy's docker-label/file-provider hybrid this
// emits a plain traefik file-provider dynamic config addressed at
// 127.0.0.1:<port> for three bare processes on the runner (api, go-api,
// query-api), matching the compose stack's SHAPE (traefik file-provider,
// PathRegexp routers, plane-split by ledger) without needing deploy-repo
// access or a docker network.
//
// Usage:
//   node ci/generate-live-e2e-plane-router.mjs <go_served_paths.tsv> \
//     --api-port 8000 --go-api-port 8001 --query-api-port 8090
//
// Prints the traefik dynamic YAML config to stdout.

import { readFileSync } from "node:fs";

function parseArgs(argv) {
    const args = { tsv: null, apiPort: "8000", goApiPort: "8001", queryApiPort: "8090" };
    const rest = [];
    for (let i = 0; i < argv.length; i++) {
        const a = argv[i];
        if (a === "--api-port") args.apiPort = argv[++i];
        else if (a === "--go-api-port") args.goApiPort = argv[++i];
        else if (a === "--query-api-port") args.queryApiPort = argv[++i];
        else rest.push(a);
    }
    args.tsv = rest[0];
    return args;
}

function escapeRegex(literal) {
    // Mirror ops's ci/bigboy/generate-plane-split-router.py: escape everything,
    // then unescape "-" (no special meaning outside a character class, and an
    // escaped "\-" is a needless YAML double-quoted-scalar escape headache).
    return literal.replace(/[.*+?^${}()|[\]\\]/g, "\\$&").replace(/\\-/g, "-");
}

function pathToRegex(path) {
    // go_served_paths.tsv path params are written "{}" (no name) -- convert
    // each to a whole-segment wildcard, same as the ops generator's {param}
    // handling.
    const parts = path.split("{}");
    return parts.map(escapeRegex).join("[^/]+");
}

function parseTsv(text) {
    const goPaths = new Set();
    const queryPaths = new Set();
    for (const line of text.split("\n")) {
        const trimmed = line.trim();
        if (!trimmed || trimmed.startsWith("#")) continue;
        const cols = trimmed.split("\t");
        if (cols.length < 3) continue;
        const [, plane, path] = cols;
        if (plane === "go-api") goPaths.add(path);
        else if (plane === "query-api") queryPaths.add(path);
    }
    return { goPaths: [...goPaths], queryPaths: [...queryPaths] };
}

function combinedRegex(paths) {
    return "^(" + paths.map(pathToRegex).join("|") + ")$";
}

function emitDynamicConfig({ goRegex, queryRegex, apiPort, goApiPort, queryApiPort }) {
    return `# GENERATED by ci/generate-live-e2e-plane-router.mjs from dev-health-ops's
# ci/go_served_paths.tsv -- do not hand-edit the rule values, regenerate.
# Traefik file-provider dynamic config for live-e2e's bare-process backends.
http:
  routers:
    go-api-paths:
      rule: "PathRegexp(\`${goRegex}\`)"
      entryPoints: [web]
      priority: 1000
      service: go-api-paths
    query-api-paths:
      rule: "PathRegexp(\`${queryRegex}\`)"
      entryPoints: [web]
      priority: 1000
      service: query-api-paths
    api-catchall:
      rule: "PathRegexp(\`^/.*$\`)"
      entryPoints: [web]
      priority: 1
      service: api-catchall
  services:
    go-api-paths:
      loadBalancer:
        servers:
          - url: "http://127.0.0.1:${goApiPort}"
    query-api-paths:
      loadBalancer:
        servers:
          - url: "http://127.0.0.1:${queryApiPort}"
    api-catchall:
      loadBalancer:
        servers:
          - url: "http://127.0.0.1:${apiPort}"
`;
}

function main() {
    const args = parseArgs(process.argv.slice(2));
    if (!args.tsv) {
        console.error(
            "usage: generate-live-e2e-plane-router.mjs <go_served_paths.tsv> [--api-port P] [--go-api-port P] [--query-api-port P]",
        );
        process.exit(2);
    }
    const text = readFileSync(args.tsv, "utf8");
    const { goPaths, queryPaths } = parseTsv(text);
    if (goPaths.length === 0) {
        console.error(
            "generate-live-e2e-plane-router: found ZERO go-api rows -- refusing to emit an empty router (go_served_paths.tsv shape may have changed)",
        );
        process.exit(1);
    }
    if (queryPaths.length === 0) {
        console.error(
            "generate-live-e2e-plane-router: found ZERO query-api rows -- refusing to emit an empty router (go_served_paths.tsv shape may have changed)",
        );
        process.exit(1);
    }
    process.stdout.write(
        emitDynamicConfig({
            goRegex: combinedRegex(goPaths),
            queryRegex: combinedRegex(queryPaths),
            apiPort: args.apiPort,
            goApiPort: args.goApiPort,
            queryApiPort: args.queryApiPort,
        }),
    );
}

main();
